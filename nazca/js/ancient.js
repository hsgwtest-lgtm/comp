/** 図柄の座標（画面座標・任意単位）を、実際の場所の緯度経度に変換 */
export function ancientSegments(g) {
  const bb = bboxOf(g.strokes);
  const k = g.size / Math.max(bb.w, bb.h);
  const cx = bb.minX + bb.w / 2; const cy = bb.minY + bb.h / 2;
  const pr = makeProjector({ lat: g.lat, lng: g.lng });
  return g.strokes.map((s) => s.map(([x, y]) => pr.toLatLng([(x - cx) * k, (y - cy) * k])));
}
