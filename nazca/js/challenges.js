const mod = (n, m) => ((n % m) + m) % m;

/** 組み込みローテーションによる日替わりお題 */
export function builtinChallenge(dayKey = challengeDayKey()) {
  if (dayKey < ORDER_V2_FROM) return byId.get(ORDER_V1[mod(dayNumber(dayKey), ORDER_V1.length)]);
  if (dayKey < ORDER_V3_FROM) return byId.get(ORDER_V2[mod(dayNumber(dayKey) - dayNumber(ORDER_V2_FROM), ORDER_V2.length)]);
  const i = dayNumber(dayKey) - dayNumber(ORDER_V3_FROM);
  if (i % 2 === 0) return byId.get(SMILE_ORDER[mod(i / 2, SMILE_ORDER.length)]);
  return byId.get(ORDER_V3[mod((i - 1) / 2, ORDER_V3.length)]);
}

export const isSmile = (t) => !!(t && t.theme === 'smile');

/**
 * Firestore の challenges/{dayKey} で上書きされたお題を検証して返す。
 * ドキュメント形式（どちらか）:
 *   { templateId: 'smile-27' }  … 組み込みのお題をそのまま使う（theme なども引き継ぐ）
 *   { name, ja, strokes: [{ p: [x1, y1, x2, y2, ...] }, ...], theme?: 'smile' }  … 線を直接書く
 */
export function templateFromDoc(dayKey, d) {
  if (!d) return null;
  if (typeof d.templateId === 'string' && byId.has(d.templateId)) return byId.get(d.templateId);
  if (!Array.isArray(d.strokes) || !d.strokes.length) return null;
  const strokes = [];
  for (const s of d.strokes) {
    const p = Array.isArray(s) ? s : s && s.p;
    if (!Array.isArray(p) || p.length < 4) continue;
    const pts = [];
    for (let i = 0; i + 1 < p.length; i += 2) {
      const x = Number(p[i]); const y = Number(p[i + 1]);
      if (Number.isFinite(x) && Number.isFinite(y)) pts.push([x, y]);
    }
    if (pts.length >= 2) strokes.push(pts);
  }
  if (!strokes.length) return null;
  const t = {
    id: String(d.id || `custom-${dayKey}`).slice(0, 40),
    name: String(d.name || 'SPECIAL').slice(0, 16).toUpperCase(),
    ja: String(d.ja || d.name || 'スペシャル').slice(0, 16),
    level: 2,
    strokes,
    custom: true,
  };
  if (d.theme === 'smile') t.theme = 'smile';
  return t;
}
